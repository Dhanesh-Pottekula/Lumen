// Bundle @aira/lumen for its two consumers.
//
//   node scripts/bundle-lumen.mjs
//   node scripts/bundle-lumen.mjs --check       # compare every output, write nothing
//
// ⚠️ AIRA-API RUNS NOTHING. The engine executes in the client's WebView, so the API needs no
// engine.js: it takes one file, canvas_film_capabilities.md, which its hand-maintained
// system-visual_film.md includes as the schema the model is shown. This script also used to write
// an engine bundle and planner/author/repair/review prompt pairs into that repo; none had a single
// Python reader, and their absence broke nothing, so they are not generated any more. Bring one
// back only alongside the code that reads it.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const workspace = path.dirname(root);
const checkOnly = process.argv.includes("--check");
const clientEngine = path.join(
  workspace,
  "aira-client/apps/aira-app/src/screens/live-mode-v2/cards/_shared/lumenEngine.ts",
);
const apiPrompts = path.join(workspace, "aira-api/app/entities/prompts");
const apiCapabilities = path.join(apiPrompts, "canvas_film_capabilities.md");

const iifePath = path.join(os.tmpdir(), `lumen-${process.pid}.iife.js`);
execFileSync(
  path.join(root, "node_modules/.bin/esbuild"),
  [
    "packages/core/src/index.ts",
    "--bundle",
    "--format=iife",
    "--global-name=Lumen",
    "--minify",
    `--outfile=${iifePath}`,
  ],
  { cwd: root, stdio: "inherit" },
);
const iife = fs.readFileSync(iifePath, "utf8");
fs.unlinkSync(iifePath);

const wrapped =
  "// @generated by aira_canvas scripts/bundle-lumen.mjs — do not edit by hand.\n" +
  "// Single-file IIFE build of @aira/lumen (packages/core), exposed as global `Lumen`.\n" +
  "export const LUMEN_ENGINE_JS: string = " +
  JSON.stringify(iife) +
  ";\n";
const bundledLumen = new Function(`${iife}; return Lumen;`)();

// ⚠️ WHAT A FILM MAY USE IS DECIDED HERE AND NOWHERE ELSE. The engine keeps every capability; this
// contract is what the authoring models read, so a kind or verb left in it WILL be used no matter
// what the prompts say, and one struck out of it cannot be — the same filtered schema is what the
// backend validates each finished scene against. Prohibitions in prose only teach the vocabulary.
//   group  — owns its children's placement, and a scene that sets it on a child is refused outright
//   effect — particles, glow and flow are decoration; a lesson moves something instead
//   spark, vignette, rings — the three attention marks that exist only to sparkle
const WITHHELD_KINDS = new Set(["group", "vector"]);
const WITHHELD_VERBS = new Set(["effect"]);
const WITHHELD_MARKS = new Set(["spark", "vignette", "rings"]);

let removed = 0;
const withhold = (node) => {
  if (Array.isArray(node)) {
    const kept = node.filter((item) => {
      const props = item && typeof item === "object" ? item.properties : undefined;
      const barred =
        WITHHELD_KINDS.has(props?.kind?.const) || WITHHELD_VERBS.has(props?.do?.const);
      if (barred) removed += 1;
      return !barred;
    });
    kept.forEach(withhold);
    node.length = 0;
    node.push(...kept);
    return;
  }
  if (!node || typeof node !== "object") return;
  if (Array.isArray(node.enum)) {
    const kept = node.enum.filter((one) => !WITHHELD_MARKS.has(one));
    if (kept.length !== node.enum.length) removed += node.enum.length - kept.length;
    node.enum = kept;
  }
  Object.values(node).forEach(withhold);
};

const contract = bundledLumen.getSimpleJsonCapabilities();
contract.objectKinds = contract.objectKinds.filter((one) => !WITHHELD_KINDS.has(one));
contract.actions = contract.actions.filter((one) => !WITHHELD_VERBS.has(one));
withhold(contract.schema);
if (removed < 7) {
  throw new Error(
    `capabilities filter struck out only ${removed} entries; the contract's shape changed and films would be offered what they must not use`,
  );
}

const capabilities = JSON.stringify(contract);
const capabilityMarkdown =
  "The fixed Lumen capabilities contract (schema, themes, assets, anchors) shared by every film stage:\n" +
  `{"capabilities": ${capabilities}}\n`;

const outputs = [
  { path: clientEngine, content: wrapped, label: "client engine" },
  { path: apiCapabilities, content: capabilityMarkdown, label: "capabilities" },
];

if (checkOnly) {
  const stale = outputs.filter((output) => {
    try {
      return fs.readFileSync(output.path, "utf8") !== output.content;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(
      `stale generated files:\n${stale.map((output) => output.path).join("\n")}`,
    );
    process.exitCode = 1;
  } else {
    console.log("Lumen runtime and prompt artifacts are synchronized");
  }
} else {
  for (const output of outputs) fs.writeFileSync(output.path, output.content);
  for (const output of outputs) {
    console.log(
      `${output.label} → ${output.path} (${(output.content.length / 1024).toFixed(0)} KB)`,
    );
  }
}
