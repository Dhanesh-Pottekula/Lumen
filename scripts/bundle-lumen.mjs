// Bundle @aira/lumen for its two consumers.
//
//   node scripts/bundle-lumen.mjs
//   node scripts/bundle-lumen.mjs --check       # compare every output, write nothing
//
// AiRA-API runs nothing. The engine executes in the client's WebView, so the API takes one file from
// the filtered contract: canvas_film_capabilities.md, the scene catalog its system-film_step.md bakes in,
// rendered by packages/core/src/simple-json/catalog.ts.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const workspace = path.join(path.dirname(path.dirname(root)), "aira_temp");
const checkOnly = process.argv.includes("--check");
const clientEngine = path.join(
  workspace,
  "aira-client/src/features/openui/components/blocks/film/lumen-engine.ts",
);
const apiPrompts = path.join(workspace, "aira-api/app/entities/prompts");
const apiCapabilities = path.join(apiPrompts, "canvas_film_capabilities.md");

const esbuild = path.join(root, "node_modules/.bin/esbuild");
const iifePath = path.join(os.tmpdir(), `lumen-${process.pid}.iife.js`);
execFileSync(
  esbuild,
  [
    "packages/core/src/index.ts",
    "--bundle",
    "--format=iife",
    "--global-name=Lumen",
    "--minify",
    `--outfile=${iifePath}`,
  ],
  { cwd: root, stdio: "inherit" },
);
const iife = fs.readFileSync(iifePath, "utf8");
fs.unlinkSync(iifePath);

// The catalog's words are for the writer only, so they are built on their own and never reach the client.
const catalogPath = path.join(os.tmpdir(), `lumen-catalog-${process.pid}.mjs`);
execFileSync(
  esbuild,
  ["packages/core/src/simple-json/catalog.ts", "--bundle", "--format=esm", "--platform=neutral", `--outfile=${catalogPath}`],
  { cwd: root, stdio: "inherit" },
);
const { renderCatalog } = await import(pathToFileURL(catalogPath).href).finally(() => fs.unlinkSync(catalogPath));

const wrapped =
  "// @generated by aira_canvas scripts/bundle-lumen.mjs — do not edit by hand.\n" +
  "// Single-file IIFE build of @aira/lumen (packages/core), exposed as global `Lumen`.\n" +
  "export const LUMEN_ENGINE_JS: string = " +
  JSON.stringify(iife) +
  ";\n";
const bundledLumen = new Function(`${iife}; return Lumen;`)();

// What a film may use is decided here and nowhere else. The engine keeps every capability; this
// contract is what the scene writer reads, so a kind or verb left in it will be used whatever the
// prompts say, and one struck out of it cannot be. Only the API's copy is filtered: the backend holds each
// scene to it, so a withheld kind or verb never reaches the engine, which checks each scene against its own.
//   group  — owns its children's placement, and a scene that sets it on a child is refused outright
//   effect — particles, glow and flow are decoration; a lesson moves something instead
//   tour   — its stops' targets escape the backend's name check, and a camera move with a label does the same job
//   trend  — an amount that rises or falls is shown by the thing itself changing, never a mark beside it
//   spark, vignette, rings — the three attention marks that exist only to sparkle
//   question — a film's words on screen name things; a chip restating the user's question never earns its place
//   svg-artwork, visual, map, vector — a thing with a real shape is a picture from the image model, never code-drawn
//   compare, scale, evidence, forces — panels beside the lesson; the scene's own pictures, sized and placed against
//     each other, moved or speaking, carry the same idea; `hero-diagram` only framed a diagram
//   diagram flow and cycle — they draw an arrow on every link, and a screen holds at most two arrows; a diagram
//     keeps `tree` and `sequence` for structures, without `links`, whose types put heads on a tree's lines
//   shape star, heart, disc, shaded — code draws only geometry; a star, a heart or a shaded ball is a picture
//   slope, dumbbell, pyramid, stack, histogram, seats, riemann, sparkline — chart forms that a bar, hbar, pie,
//     line, function or units chart says more plainly; `majority` only ever marked `seats`
//   callout — a `label` names a thing, and one way to name it is clearer than two; `title`, `side`, `route`
//     and `style` only ever shaped a callout's note, and `pointer` never drew them
//   outline, spotlight, box, converge — attention verbs that `trace`, `dim`, `encircle` and `brackets` already
//     cover; withheld on the attention verb alone, since `outline` is also an appearance and `box` a word elsewhere
// A timeline stays in the contract: the planner asks for one only where a step needs it, and the backend
// only lints how many steps did, never refusing one.
const WITHHELD_KINDS = new Set([
  "group", "vector", "svg-artwork", "map", "visual", "question", "compare", "scale", "evidence", "forces",
]);
const WITHHELD_LAYOUTS = new Set(["flow", "cycle"]);
const WITHHELD_DIAGRAM_KEYS = new Set(["links"]);
const WITHHELD_SHAPES = new Set(["star", "heart", "disc", "shaded"]);
const WITHHELD_VERBS = new Set(["effect", "tour", "trend"]);
const WITHHELD_MARKS = new Set(["spark", "vignette", "rings", "map", "hero-diagram", "callout"]);
const WITHHELD_ATTENTION_KEYS = new Set(["title", "side", "route", "style"]);
const WITHHELD_ATTENTION_VERBS = new Set(["outline", "spotlight", "box", "converge"]);
const WITHHELD_CHARTS = new Set(["slope", "dumbbell", "pyramid", "stack", "histogram", "seats", "riemann", "sparkline"]);
const WITHHELD_CHART_KEYS = new Set(["majority"]);
const chartsOf = (props) => (props?.kind?.const === "chart" ? (props.chart?.const ? [props.chart.const] : (props.chart?.enum ?? [])) : []);

let removed = 0;
const withhold = (node) => {
  if (Array.isArray(node)) {
    const kept = node.filter((item) => {
      const props = item && typeof item === "object" ? item.properties : undefined;
      const charts = chartsOf(props);
      const barred =
        WITHHELD_KINDS.has(props?.kind?.const) ||
        WITHHELD_VERBS.has(props?.do?.const) ||
        (charts.length > 0 && charts.every((chart) => WITHHELD_CHARTS.has(chart)));
      if (barred) removed += 1;
      return !barred;
    });
    kept.forEach(withhold);
    node.length = 0;
    node.push(...kept);
    return;
  }
  if (!node || typeof node !== "object") return;
  if (chartsOf(node.properties).some((chart) => WITHHELD_CHARTS.has(chart))) {
    node.properties.chart.enum = node.properties.chart.enum.filter((chart) => !WITHHELD_CHARTS.has(chart));
    for (const key of WITHHELD_CHART_KEYS) delete node.properties[key];
    removed += 1;
  }
  if (node.properties?.kind?.const === "diagram") {
    node.properties.layout.enum = node.properties.layout.enum.filter((layout) => !WITHHELD_LAYOUTS.has(layout));
    for (const key of WITHHELD_DIAGRAM_KEYS) delete node.properties[key];
    removed += 1;
  }
  if (node.properties?.kind?.const === "shape" || node.properties?.motion?.const === "morph") {
    for (const key of ["shape", "appearance"]) {
      const field = node.properties[key];
      if (field?.enum) field.enum = field.enum.filter((one) => !WITHHELD_SHAPES.has(one));
    }
    removed += 1;
  }
  const verb = node.properties?.do?.const === "attention" ? node.properties.verb : undefined;
  if (verb?.const === "pointer" || verb?.enum?.includes("callout")) {
    for (const key of WITHHELD_ATTENTION_KEYS) delete node.properties[key];
  }
  if (verb?.enum?.some((one) => WITHHELD_ATTENTION_VERBS.has(one))) {
    const kept = verb.enum.filter((one) => !WITHHELD_ATTENTION_VERBS.has(one));
    removed += verb.enum.length - kept.length;
    verb.enum = kept;
  }
  if (Array.isArray(node.enum)) {
    const kept = node.enum.filter((one) => !WITHHELD_MARKS.has(one));
    if (kept.length !== node.enum.length) removed += node.enum.length - kept.length;
    node.enum = kept;
  }
  Object.values(node).forEach(withhold);
};

const capabilities = bundledLumen.getSimpleJsonCapabilities();
const contract = {
  compositions: capabilities.compositions.filter((one) => !WITHHELD_MARKS.has(one)),
  objectKinds: capabilities.objectKinds.filter((one) => !WITHHELD_KINDS.has(one)),
  actions: capabilities.actions.filter((one) => !WITHHELD_VERBS.has(one)),
  mathTextCommands: capabilities.mathTextCommands,
  expressionFunctions: capabilities.expressionFunctions,
  expressionConstants: capabilities.expressionConstants,
  schema: capabilities.schema,
};
withhold(contract.schema);
if (removed < 7) {
  throw new Error(
    `capabilities filter struck out only ${removed} entries; the contract's shape changed and films would be offered what they must not use`,
  );
}
const schemaText = JSON.stringify(contract.schema);
for (const kind of WITHHELD_KINDS) {
  if (schemaText.includes(`"const":"${kind}"`) || contract.objectKinds.includes(kind)) throw new Error(`the contract still offers the withheld kind ${kind}`);
}
const offeredCharts = new Set((contract.schema.$defs?.object?.oneOf ?? []).flatMap((variant) => chartsOf(variant.properties)));
for (const chart of WITHHELD_CHARTS) {
  if (offeredCharts.has(chart)) throw new Error(`the contract still offers the withheld chart ${chart}`);
}
const actionVariants = contract.schema.properties?.scenes?.items?.properties?.beats?.items?.properties?.actions?.items?.oneOf ?? [];
const variantsOf = (test) => [...(contract.schema.$defs?.object?.oneOf ?? []), ...actionVariants].filter((variant) => test(variant.properties ?? {}));
for (const variant of variantsOf((props) => props.kind?.const === "diagram")) {
  if (variant.properties.layout.enum.some((layout) => WITHHELD_LAYOUTS.has(layout)) || "links" in variant.properties) throw new Error("the contract still offers a diagram that draws arrows");
}
for (const variant of variantsOf((props) => props.kind?.const === "shape" || props.motion?.const === "morph")) {
  if ([variant.properties.shape, variant.properties.appearance].some((field) => field?.enum?.some((one) => WITHHELD_SHAPES.has(one)))) throw new Error("the contract still offers a shape that is not geometry");
}
const attentionVerbs = actionVariants.flatMap((variant) =>
  variant.properties?.do?.const === "attention" ? (variant.properties.verb?.enum ?? [variant.properties.verb?.const]) : [],
);
for (const verb of WITHHELD_ATTENTION_VERBS) {
  if (attentionVerbs.includes(verb)) throw new Error(`the contract still offers the withheld attention verb ${verb}`);
}

// The catalog renders only what the filtered schema offers and throws on any kind, verb or value it
// cannot describe; these checks catch a withheld name surviving in its hand-written words.
const capabilityMarkdown = renderCatalog(contract);
const offered = (pattern) => new RegExp(pattern, "m").test(capabilityMarkdown);
for (const kind of WITHHELD_KINDS) {
  if (offered(`^${kind} \\{`) || capabilityMarkdown.includes(`kind: "${kind}"`) || capabilityMarkdown.includes(`\`${kind}\` kind`)) {
    throw new Error(`the catalog renders the withheld kind ${kind}`);
  }
}
for (const verb of WITHHELD_VERBS) {
  if (offered(`^${verb} \\{`) || capabilityMarkdown.includes(`do: "${verb}"`) || capabilityMarkdown.includes(`\`${verb}\``)) {
    throw new Error(`the catalog renders the withheld verb ${verb}`);
  }
}
for (const mark of WITHHELD_MARKS) {
  if (capabilityMarkdown.includes(`'${mark}'`) || capabilityMarkdown.includes(`\`"${mark}"\``) || capabilityMarkdown.includes(`\`${mark}\``)) {
    throw new Error(`the catalog renders the withheld value ${mark}`);
  }
}
for (const chart of WITHHELD_CHARTS) {
  if (capabilityMarkdown.includes(`\`${chart}\``) || capabilityMarkdown.includes(`"${chart}"`) || capabilityMarkdown.includes(`'${chart}'`)) {
    throw new Error(`the catalog renders the withheld chart ${chart}`);
  }
}
const attentionEntry = capabilityMarkdown.slice(capabilityMarkdown.indexOf("\nattention {"), capabilityMarkdown.indexOf("\npointer {"));
for (const verb of WITHHELD_ATTENTION_VERBS) {
  if (capabilityMarkdown.includes(`\`${verb}\``) || attentionEntry.includes(`'${verb}'`) || attentionEntry.includes(`\`"${verb}"\``)) {
    throw new Error(`the catalog renders the withheld attention verb ${verb}`);
  }
}
if (capabilityMarkdown.includes("svg-artwork")) throw new Error("the catalog mentions the withheld svg-artwork");

const outputs = [
  { path: clientEngine, content: wrapped, label: "client engine" },
  { path: apiCapabilities, content: capabilityMarkdown, label: "capabilities" },
];

if (checkOnly) {
  const stale = outputs.filter((output) => {
    try {
      return fs.readFileSync(output.path, "utf8") !== output.content;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(
      `stale generated files:\n${stale.map((output) => output.path).join("\n")}`,
    );
    process.exitCode = 1;
  } else {
    console.log("Lumen runtime and prompt artifacts are synchronized");
  }
} else {
  for (const output of outputs) fs.writeFileSync(output.path, output.content);
  for (const output of outputs) {
    console.log(
      `${output.label} → ${output.path} (${(output.content.length / 1024).toFixed(0)} KB)`,
    );
  }
}
